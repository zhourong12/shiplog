export type Lang = "zh" | "en";
export type TranslationKey = Key;
type Translate = (key: Key, vars?: Record<string, string | number>) => string;

const I18nContext = createContext<{ lang: Lang; setLang: (lang: Lang) => void; t: Translate }>({
  lang: "zh",
  setLang: () => undefined,
  t: (key) => zh[key],
});

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("shiplog-lang");
    if (saved === "zh" || saved === "en") return saved;
  } catch {
    // Ignore unavailable storage.
  }
  return navigator.language?.toLowerCase().startsWith("zh") === false ? "en" : "zh";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try {
      localStorage.setItem("shiplog-lang", next);
    } catch {
      // Ignore unavailable storage.
    }
    document.documentElement.lang = next === "zh" ? "zh-CN" : "en";
  }, []);
  const t = useCallback<Translate>(
    (key, vars) => {
      const template = (lang === "zh" ? zh : en)[key];
      if (!vars) return template;
      return template.replace(/\{(\w+)\}/g, (match, name: string) =>
        vars[name] === undefined ? match : String(vars[name]),
      );
    },
    [lang],
  );
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
